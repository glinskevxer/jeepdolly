"""Generate the glossary from the vocabulary the code already declares.

The office's words are not in a document, they are in the type system: every
``StrEnum`` in this package is a closed list of terms somebody at the counter
uses out loud. A glossary written separately would drift from them within a
month.

So this walks the package for enumerations, takes each member's value as the
term and the class docstring as the sense, and writes the document. Terms that
mean something specific and are not enumerations, like the bridge formula or the
crossover, are listed by hand at the end because they are ideas rather than
values.
"""

from __future__ import annotations

import ast
import sys
from dataclasses import dataclass
from pathlib import Path

from jeepdolly.tools.document import Document
from jeepdolly.tools.walk import module_of, parse, repo_root, source_files

__all__ = [
    "DOCUMENT",
    "DOC_NAME",
    "EXTRA",
    "Term",
    "doc_path",
    "enum_terms",
    "main",
    "render",
    "write",
]

#: Where the glossary is committed.
DOC_NAME = "glossary.md"

#: Ideas the office names that are not a value in an enumeration.
EXTRA: tuple[tuple[str, str], ...] = (
    (
        "bridge formula",
        "The federal rule that says how much a run of axles may weigh given how"
        " far apart the first and last of them are.",
    ),
    (
        "crossover",
        "The spread past which adding an axle stops raising what the bridge"
        " formula allows. Twelve times N times N minus one, in feet.",
    ),
    (
        "extreme",
        "The distance from the first axle of a group to the last, measured centre to centre.",
    ),
    (
        "frost law",
        "A seasonal order cutting the axle limits while the subgrade thaws,"
        " usually to sixty percent for about six weeks in spring.",
    ),
    (
        "headroom",
        "How much more a carrier may be charged before the account hits its credit floor.",
    ),
    (
        "jeep dolly",
        "An axle set dropped between the tractor and the trailer to spread gross"
        " weight across more axles.",
    ),
    (
        "nondivisible",
        "A load that cannot be taken apart and hauled in two trips. Only a"
        " nondivisible load may be permitted over the statutory weight.",
    ),
    (
        "superload",
        "A load big enough that the application goes to engineering review"
        " rather than being written over the counter.",
    ),
)


@dataclass(frozen=True, slots=True, order=True)
class Term:
    """One word the office uses, and where it is defined."""

    word: str
    sense: str
    where: str = ""

    def __str__(self) -> str:
        tail = f" ({self.where})" if self.where else ""
        return f"{self.word}{tail}: {self.sense}"


def _first_sentence(text: str) -> str:
    """The first sentence of a docstring, on one line."""
    tidy = " ".join(text.split())
    head, dot, _ = tidy.partition(". ")
    return (head + ".") if dot else tidy


def enum_terms() -> list[Term]:
    """Every member of every enumeration in the package."""
    out: list[Term] = []
    for path in source_files():
        module = module_of(path)
        for node in ast.walk(parse(path)):
            if not isinstance(node, ast.ClassDef):
                continue
            bases = {ast.unparse(base) for base in node.bases}
            if not bases & {"StrEnum", "Enum", "IntEnum"}:
                continue
            sense = _first_sentence(ast.get_docstring(node) or node.name)
            for member in node.body:
                if not isinstance(member, ast.Assign):
                    continue
                value = member.value
                if not isinstance(value, ast.Constant) or not isinstance(value.value, str):
                    continue
                out.append(Term(word=value.value, sense=sense, where=f"{module}.{node.name}"))
    return sorted(out)


def render() -> str:
    """The whole glossary as text."""
    lines = [
        "# jeepdolly glossary",
        "",
        "Generated by `tools/build_glossary.py` from the enumerations in the",
        "package, plus the ideas listed by hand at the end of that file.",
        "",
        "## words with a closed list of values",
        "",
        "| word | sense | declared in |",
        "| --- | --- | --- |",
    ]
    for term in enum_terms():
        lines.append(f"| {term.word} | {term.sense} | `{term.where}` |")
    lines.append("")
    lines.append("## ideas")
    lines.append("")
    lines.append("| word | sense |")
    lines.append("| --- | --- |")
    for word, sense in EXTRA:
        lines.append(f"| {word} | {' '.join(sense.split())} |")
    return "\n".join(lines).rstrip() + "\n"


def doc_path() -> Path:
    """Where the glossary lives."""
    return repo_root() / "docs" / DOC_NAME


DOCUMENT = Document(name="build_glossary", render=render, path_of=lambda: doc_path())


def write() -> Path:
    """Write the document out and hand back where it went."""
    return DOCUMENT.write()


def main(argv: list[str] | None = None) -> int:
    """Write the document, or check the committed one is current."""
    return DOCUMENT.main(argv)


if __name__ == "__main__":
    sys.exit(main())
